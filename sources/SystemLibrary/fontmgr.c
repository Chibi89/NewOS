static void fm_dbg(const char *s) {
    while (s && *s) {
        unsigned char al = (unsigned char)*s++;
        __asm__ volatile("outb %0, %1" :: "a"(al), "Nd"((unsigned short)0x3F8));
    }
}

static void fontmgr_load_ttf(const kernel_api_t *api) {
    if (g_ttf_tried || !api || !api->vfs_read_entire_file) return;
    g_ttf_tried = true;
    fm_dbg("[FM] load_ttf\n");
    const char *paths[] = {
        "C:\\NewOS\\Resources\\Fonts\\SANS.TTF",
        "/NewOS/Resources/Fonts/SANS.TTF",
        "C:\\NewOS\\Fonts\\SANS.TTF"
    };
    for (int i = 0; i < 3; i++) {
        uint32_t sz = 0;
        uint8_t *buf = api->vfs_read_entire_file(paths[i], &sz);
        if (buf && sz > 1024) {
            fm_dbg("[FM] ttf_read_ok\n");
            if (stbtt_InitFont(&g_ttf_info, buf, stbtt_GetFontOffsetForIndex(buf, 0))) {
                fm_dbg("[FM] ttf_init_ok\n");
                g_ttf_data = buf;
                g_ttf_ready = true;
                g_ttf_cache = (ttf_cache_slot_t *)api->kmalloc(sizeof(ttf_cache_slot_t) * TTF_CACHE_SLOTS);
                if (g_ttf_cache) fm_memset(g_ttf_cache, 0, sizeof(ttf_cache_slot_t) * TTF_CACHE_SLOTS);
                fm_dbg("[FM] ttf_ready\n");
                return;
            }
        }
        if (buf && api->kfree) api->kfree(buf);
    }
}

static void fontmgr_load_ufnt(const kernel_api_t *api) {
    if (g_ufnt_data || !api || !api->vfs_read_entire_file) return;
    const char *paths[] = {
        "C:\\NewOS\\Resources\\Fonts\\UNICODE.FNT",
        "/NewOS/Resources/Fonts/UNICODE.FNT",
        "C:\\NewOS\\Font\\UNICODE.FNT"
    };
    for (int i = 0; i < 3; i++) {
        uint32_t sz = 0;
        uint8_t *buf = api->vfs_read_entire_file(paths[i], &sz);
        if (buf && sz >= 1032 && buf[0] == 'U' && buf[1] == 'F' && buf[2] == 'N' && buf[3] == 'T') {
            g_ufnt_data = buf;
            g_ufnt_size = sz;
            return;
        }
        if (buf && api->kfree) api->kfree(buf);
    }
}

static int fontmgr_dispatch(const kernel_api_t *api, fontmgr_params_t *p) {
    if (!p) return -1;
    g_fm_api = api;
    if (p->cmd == FONTMGR_CMD_INIT) {
        fontmgr_load_ufnt(api);
        fontmgr_load_ttf(api);
        return 0;
    }

    if (p->cmd == FONTMGR_CMD_GET_TTF_GLYPH) {
        if (!g_ttf_tried) fontmgr_load_ttf(api);
        p->found = false;
        if (!g_ttf_ready || !p->ttf_bitmap || p->ttf_cap <= 0) return -1;

        int ph = p->pixel_height;
        if (ph < 10) ph = 14;
        if (ph > 36) ph = 36;
        uint32_t cp = p->codepoint;
        uint32_t slot = ((cp * 31u) ^ (uint32_t)ph) & (TTF_CACHE_SLOTS - 1);

        if (g_ttf_cache && g_ttf_cache[slot].valid &&
            g_ttf_cache[slot].cp == cp && g_ttf_cache[slot].px_h == ph) {
            ttf_cache_slot_t *c = &g_ttf_cache[slot];
            int n = c->w * c->h;
            if (n > p->ttf_cap) n = p->ttf_cap;
            if (n > 0) fm_memcpy(p->ttf_bitmap, c->bmp, (size_t)n);
            p->ttf_w = c->w; p->ttf_h = c->h;
            p->ttf_xoff = c->xoff; p->ttf_yoff = c->yoff;
            p->ttf_advance = c->adv;
            p->found = true;
            return 0;
        }

        int gid = stbtt_FindGlyphIndex(&g_ttf_info, (int)cp);
        if (gid == 0 && cp != ' ') return 0; // Lascia fallback a UNICODE.FNT

        float scale = stbtt_ScaleForPixelHeight(&g_ttf_info, (float)ph);
        int adv = 0, lsb = 0;
        stbtt_GetGlyphHMetrics(&g_ttf_info, gid, &adv, &lsb);
        int adv_px = (int)(adv * scale + 0.5f);
        if (adv_px < 2) adv_px = ph / 3;

        int gw = 0, gh = 0, xoff = 0, yoff = 0;
        uint8_t *bmp = stbtt_GetGlyphBitmap(&g_ttf_info, 0, scale, gid, &gw, &gh, &xoff, &yoff);
        if (gw > 48) gw = 48;
        if (gh > 48) gh = 48;
        int n = gw * gh;
        if (n > p->ttf_cap) n = p->ttf_cap;
        if (bmp && n > 0) fm_memcpy(p->ttf_bitmap, bmp, (size_t)n);
        if (bmp) stbtt_FreeBitmap(bmp, NULL);

        p->ttf_w = gw; p->ttf_h = gh;
        p->ttf_xoff = xoff; p->ttf_yoff = yoff;
        p->ttf_advance = adv_px;
        p->found = true;

        if (g_ttf_cache && n <= TTF_MAX_BMP) {
            ttf_cache_slot_t *c = &g_ttf_cache[slot];
            c->cp = cp; c->px_h = ph;
            c->w = gw; c->h = gh;
            c->xoff = xoff; c->yoff = yoff; c->adv = adv_px;
            if (n > 0) fm_memcpy(c->bmp, p->ttf_bitmap, (size_t)n);
            c->valid = true;
        }
        return 0;
    }

    if (p->cmd == FONTMGR_CMD_GET_GLYPH) {
        if (!g_ufnt_data) fontmgr_load_ufnt(api);

        uint32_t cp = p->codepoint;
        // 1. Tabella pixel-perfect integrata (Latin-1 + Tipografia + Frecce)
        for (size_t i = 0; i < sizeof(g_unicode_glyphs) / sizeof(g_unicode_glyphs[0]); i++) {
            if (g_unicode_glyphs[i].cp == cp) {
                for (int r = 0; r < 16; r++) p->glyph[r] = g_unicode_glyphs[i].rows[r];
                p->found = true;
                return 0;
            }
        }

        // 2. Font Unicode esterno C:\NewOS\Resources\Fonts\UNICODE.FNT (11 blocchi BMP)
        if (g_ufnt_data && cp < 0x10000) {
            uint32_t blk = cp >> 8;
            uint32_t idx = cp & 0xFF;
            const uint32_t *offsets = (const uint32_t *)(g_ufnt_data + 8);
            uint32_t off = offsets[blk];
            if (off >= 1032 && off + (idx + 1) * 16 <= g_ufnt_size) {
                const uint8_t *g = g_ufnt_data + off + idx * 16;
                uint8_t any = 0;
                for (int r = 0; r < 16; r++) {
                    p->glyph[r] = g[r];
                    any |= g[r];
                }
                if (any != 0) {
                    p->found = true;
                    return 0;
                }
            }
        }

        // 3. Fallback pulito □ (box Unicode) per altri script/emoji non presenti
        for (int r = 0; r < 16; r++) p->glyph[r] = g_tofu_glyph[r];
        p->found = true;
        return 0;
    }
    return -1;
}
