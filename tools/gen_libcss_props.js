const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const PROPS_DIR = path.join(ROOT, 'third_party', 'netsurf', 'netsurf-all-3.11', 'libcss', 'src', 'parse', 'properties');
const GEN_BIN = path.join(ROOT, 'build', 'gen_parser.exe');
const PROPS_GEN = path.join(PROPS_DIR, 'properties.gen');

const lines = fs.readFileSync(PROPS_GEN, 'utf8').split(/\r?\n/);
let count = 0;
for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const colon = trimmed.indexOf(':');
    if (colon <= 0) continue;
    const prop = trimmed.slice(0, colon).trim();
    const outFile = path.join(PROPS_DIR, `autogenerated_${prop}.c`);
    execFileSync(GEN_BIN, ['-o', outFile, trimmed], { stdio: 'inherit' });
    count++;
}
console.log(`[OK] Generati ${count} parser CSS ufficiali (autogenerated_*.c) per libcss`);
