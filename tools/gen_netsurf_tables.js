const fs = require('fs');
const path = require('path');

const NS_ROOT = path.join(__dirname, '..', 'third_party', 'netsurf', 'netsurf-all-3.11');

function genAliases() {
    const inFile = path.join(NS_ROOT, 'libparserutils', 'build', 'Aliases');
    const outFile = path.join(NS_ROOT, 'libparserutils', 'src', 'charset', 'aliases.inc');
    const lines = fs.readFileSync(inFile, 'utf8').split(/\r?\n/);

    const charsets = new Map();
    for (const line of lines) {
        if (!line || line.startsWith('#')) continue;
        const trimmed = line.trim();
        if (!trimmed) continue;
        const parts = trimmed.split(/\s+/);
        const canon = parts.shift();
        const mibenum = parts.shift();
        charsets.set(canon, { mibenum, aliases: parts });
    }

    const unicodeRe = [/^ISO-10646-UCS-[24]$/, /^UTF-16/, /^UTF-8$/, /^UTF-32/];
    let unicodeExp = '';
    let out = '/* Auto-generated by tools/gen_netsurf_tables.js */\n\n';
    out += 'static parserutils_charset_aliases_canon canonical_charset_names[] = {\n';

    const aliases = new Map();
    let canonNr = 0;
    const sortedCanons = Array.from(charsets.keys()).sort();
    for (const canon of sortedCanons) {
        const { mibenum, aliases: aliasList } = charsets.get(canon);
        out += `\t{ ${mibenum}, ${canon.length}, "${canon}" },\n`;
        if (unicodeRe.some(re => re.test(canon))) {
            unicodeExp += `((x) == ${mibenum}) || `;
        }
        const normCanon = canon.toLowerCase().replace(/[^a-z0-9]/g, '');
        aliases.set(normCanon, canonNr);
        for (const a of aliasList) {
            const na = a.toLowerCase().replace(/[^a-z0-9]/g, '');
            aliases.set(na, canonNr);
        }
        canonNr++;
    }
    out += `};\n\nstatic const uint16_t charset_aliases_canon_count = ${canonNr};\n\n`;
    out += 'typedef struct {\n\tuint16_t name_len;\n\tconst char *name;\n\tparserutils_charset_aliases_canon *canon;\n} parserutils_charset_aliases_alias;\n\n';
    out += 'static parserutils_charset_aliases_alias charset_aliases[] = {\n';

    let aliasCount = 0;
    for (const a of Array.from(aliases.keys()).sort()) {
        const cnr = aliases.get(a);
        out += `\t{ ${a.length}, "${a}", &canonical_charset_names[${cnr}] },\n`;
        aliasCount++;
    }
    out += '};\n\n';
    if (unicodeExp.endsWith(' || ')) unicodeExp = unicodeExp.slice(0, -4);
    out += `static const uint16_t charset_aliases_count = ${aliasCount};\n\n`;
    out += `#define MIBENUM_IS_UNICODE(x) (${unicodeExp})\n`;

    fs.writeFileSync(outFile, out, 'utf8');
    console.log(`[OK] Generato aliases.inc (${canonNr} charset, ${aliasCount} alias)`);
}

function genEntities() {
    const inFile = path.join(NS_ROOT, 'libhubbub', 'build', 'Entities');
    const outFile = path.join(NS_ROOT, 'libhubbub', 'src', 'tokeniser', 'entities.inc');
    const lines = fs.readFileSync(inFile, 'utf8').split(/\r?\n/);

    const entities = new Map();
    for (const line of lines) {
        if (!line || line.startsWith('#')) continue;
        const trimmed = line.trim();
        if (!trimmed) continue;
        const parts = trimmed.split(/\s+/);
        const entity = parts[0];
        const code = parts[1];
        if (entity && code !== undefined) entities.set(entity, code);
    }

    let heapIndex = 0;
    const nodeList = [];
    function insertNode(parent, key, code) {
        let pivot = '', tail = '';
        if (key.length === 1) { pivot = key; tail = ''; }
        else if (key.length > 1) { pivot = key[0]; tail = key.slice(1); }

        if (!parent) {
            parent = { pivot, heapindex: heapIndex++ };
            nodeList.push(parent);
        }
        if (pivot < parent.pivot) {
            parent.lt = insertNode(parent.lt, key, code);
        } else if (pivot === parent.pivot) {
            if (pivot === '') {
                parent.value = code;
            } else if (tail.length === 0) {
                parent.value = code;
                parent.eq = insertNode(parent.eq, tail, code);
            } else {
                parent.eq = insertNode(parent.eq, tail, code);
            }
        } else {
            parent.gt = insertNode(parent.gt, key, code);
        }
        return parent;
    }

    let trie = null;
    for (const [k, v] of entities.entries()) {
        trie = insertNode(trie, k, v);
    }

    let out = '/* Auto-generated by tools/gen_netsurf_tables.js */\n\n';
    out += 'static hubbub_entity_node dict[] = {\n';
    for (const n of nodeList) {
        const lt = n.lt ? n.lt.heapindex : -1;
        const eq = n.eq ? n.eq.heapindex : -1;
        const gt = n.gt ? n.gt.heapindex : -1;
        const split = n.pivot ? n.pivot.charCodeAt(0) : 0;
        const val = n.value !== undefined ? n.value : 0;
        out += `\t{ ${split}, ${lt}, ${eq}, ${gt}, ${val} },\n`;
    }
    out += '};\n\n';
    out += `static int32_t dict_root = ${trie ? trie.heapindex : -1};\n`;

    fs.writeFileSync(outFile, out, 'utf8');
    console.log(`[OK] Generato entities.inc (${entities.size} entita', ${nodeList.length} nodi trie)`);
}

genAliases();
genEntities();

function genElementTypes() {
    const inFile = path.join(NS_ROOT, 'libhubbub', 'src', 'treebuilder', 'element-type.gperf');
    const outFile = path.join(NS_ROOT, 'libhubbub', 'src', 'treebuilder', 'autogenerated-element-type.c');
    const lines = fs.readFileSync(inFile, 'utf8').split(/\r?\n/);

    let inBody = false;
    const entries = [];
    for (const line of lines) {
        const t = line.trim();
        if (t === '%%') { inBody = true; continue; }
        if (!inBody || !t || t.startsWith('/*')) continue;
        const parts = t.split(',');
        if (parts.length >= 2) {
            entries.push({ name: parts[0].trim(), type: parts[1].trim() });
        }
    }
    entries.sort((a, b) => a.name.localeCompare(b.name));

    let out = '/* Auto-generated by tools/gen_netsurf_tables.js */\n';
    out += '#include <string.h>\n#include "treebuilder/element-type.h"\n\n';
    out += 'static const struct element_type_map wordlist[] = {\n';
    for (const e of entries) {
        out += `\t{ "${e.name}", ${e.type} },\n`;
    }
    out += '};\n\n';
    out += 'static const struct element_type_map *hubbub_element_type_generated_lookup(const char *str, size_t len) {\n';
    out += '\tsize_t l = 0, r = sizeof(wordlist) / sizeof(wordlist[0]);\n';
    out += '\twhile (l < r) {\n';
    out += '\t\tsize_t m = l + (r - l) / 2;\n';
    out += '\t\tconst char *w = wordlist[m].name;\n';
    out += '\t\tsize_t wl = strlen(w);\n';
    out += '\t\tsize_t ml = (len < wl) ? len : wl;\n';
    out += '\t\tint c = strncasecmp(str, w, ml);\n';
    out += '\t\tif (c == 0) {\n';
    out += '\t\t\tif (len == wl) return &wordlist[m];\n';
    out += '\t\t\tc = (len < wl) ? -1 : 1;\n';
    out += '\t\t}\n';
    out += '\t\tif (c < 0) r = m;\n';
    out += '\t\telse l = m + 1;\n';
    out += '\t}\n';
    out += '\treturn NULL;\n';
    out += '}\n';

    fs.writeFileSync(outFile, out, 'utf8');
    console.log(`[OK] Generato autogenerated-element-type.c (${entries.length} tag HTML5)`);
}

genElementTypes();
